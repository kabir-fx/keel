// Writes src/fontwidths.ts: the advance width of each character in the faces the pictures
// draw SVG text in, measured once in the system Chrome from the @fontsource files the app
// loads. The renderers lay text out from this table, so the same spec gives the same layout
// in a test (happy-dom has no fonts) and in the browser.
//
//   node pictures/scripts/fontwidths.mjs        (from workspace/)

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const here = dirname(fileURLToPath(import.meta.url));
const modules = join(here, '..', '..', 'node_modules', '@fontsource');

const FACES = {
  ui400: ['Inter', 400, 'inter/files/inter-latin-400-normal.woff2'],
  ui500: ['Inter', 500, 'inter/files/inter-latin-500-normal.woff2'],
  ui600: ['Inter', 600, 'inter/files/inter-latin-600-normal.woff2'],
  ui700: ['Inter', 700, 'inter/files/inter-latin-700-normal.woff2'],
  head600: ['Space Grotesk', 600, 'space-grotesk/files/space-grotesk-latin-600-normal.woff2'],
  head700: ['Space Grotesk', 700, 'space-grotesk/files/space-grotesk-latin-700-normal.woff2'],
};

let chars = '';
for (let c = 0x20; c <= 0x7e; c++) chars += String.fromCharCode(c);
for (let c = 0xa0; c <= 0xff; c++) chars += String.fromCharCode(c);
for (let c = 0x2010; c <= 0x2027; c++) chars += String.fromCharCode(c);
for (let c = 0x2030; c <= 0x203a; c++) chars += String.fromCharCode(c);

const css = Object.entries(FACES)
  .map(([, [family, weight, file]]) => {
    const b64 = readFileSync(join(modules, file)).toString('base64');
    return `@font-face{font-family:'${family}';font-weight:${weight};src:url(data:font/woff2;base64,${b64}) format('woff2');}`;
  })
  .join('\n');

const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage();
await page.setContent(`<style>${css}</style><p>x</p>`);
const widths = await page.evaluate(
  async ({ faces, chars }) => {
    const ctx = document.createElement('canvas').getContext('2d');
    const out = {};
    for (const [key, [family, weight]] of Object.entries(faces)) {
      const font = `${weight} 1000px '${family}'`;
      await document.fonts.load(font, chars);
      if (!document.fonts.check(font)) throw new Error(`font not loaded: ${font}`);
      ctx.font = font;
      out[key] = [...chars].map((ch) => Math.round(ctx.measureText(ch).width));
    }
    return out;
  },
  { faces: FACES, chars },
);
await browser.close();

const lines = [
  '/* Generated by scripts/fontwidths.mjs. Do not edit: run the script again. */',
  '',
  '/** The characters measured, in order. */',
  `export const CHARS = ${JSON.stringify(chars)};`,
  '',
  '/** Advance widths in thousandths of an em, one per character of CHARS. */',
  'export const WIDTHS = {',
  ...Object.entries(widths).map(([k, v]) => `  ${k}: [${v.join(',')}],`),
  '} as const;',
  '',
];
writeFileSync(join(here, '..', 'src', 'fontwidths.ts'), lines.join('\n'));
console.log(`wrote ${Object.keys(widths).length} faces x ${chars.length} characters`);
